/**
 * 覆盖补齐独立于代码增量，代码仓与系统知识仓共享调查和验收要求。
 */
export function buildBackfillInstructions(data: any): string[] {
  if (data.mode !== "backfill") return [];

  const repoPath = data.path;
  const writeScope = data.repoType === "system_knowledge"
    ? `仅写入目标系统知识仓 ${repoPath} 的知识文档与索引`
    : `仅写入目标仓库 ${repoPath}/docs/knowledge/`;

  return [
    `## 知识覆盖补齐模式（backfill）`,
    ``,
    `- 本任务不是增量核验，也不是删除重建；目标是补齐首次建库或历次维护遗漏的知识，保留人工内容与已有有效结论。`,
    `- 本节优先于技能中的无变更跳过与已有文档 scope 门槛：即使 from 与 to 相同、没有新增提交或六类目录已存在，也必须执行源码覆盖调查。git diff 和已有文档只能提供线索，不能限定发现范围。`,
    `- 先读取 project-knowledge-maintainer 的 references/coverage.md、references/layout.md 与 references/quality.md；按源码真实行为发现主题，不以现有 Markdown 清单代替扫描。`,
    ``,
    `### 从源码发现，再对照知识`,
    ``,
    `- 从入口装配、注册表、公共导出、路由、CLI/工具动作、消息消费者、回调和定时任务建立行为清单；结合测试、状态读写、配置、日志和错误码反查遗漏。`,
    `- 系统知识仓需横向核对代码仓归属、未登记领域、跨仓调用与消息交接；代码仓需核对本仓完整行为，允许只读兄弟仓验证边界。`,
    `- 对每个重要主题核对是否已有可用文档，区分已调查、需补充、未调查和有依据的不适用；不能因为主题没有现存 scope 或引用就略过。`,
    `- 优先补齐缺失的端到端流程、关键分支、失败传播与恢复路径、接口/事件契约、公共规则、模块职责和数据引用；结论绑定真实源码路径与符号，未知外部实现不写成事实。`,
    `- 采用六大分类规范，维护 index.md 与 overview.md；独立业务主题合理拆分，已有专题优先局部补充，不重复建页，不按固定篇数凑数，也不只创建空目录或模板。`,
    `- 宿主支持子代理时，按类别委派覆盖核验与缺口补充，广度发现可按模块并行；主智能体汇总主题与证据并反向验收，避免多个代理同时编辑同一文件。`,
    ``,
    `### 写入边界与补齐验收`,
    ``,
    `- ${writeScope}；其他仓库只能只读核验，不得因跨仓关联擅自修改、发布或推进其他仓库检查点，也不得再次调用流水线。`,
    `- 在知识索引保留紧凑的主题覆盖表：主题、真实入口线索、对应文档或小节、调查状态与缺口；未深入项保留下一步定位，不链接尚未创建的文件。`,
    `- 写入后重新从源码入口清单反向核对覆盖，运行 links.verify 并修复断链；类别确无对象时在索引和报告中说明证据，不编造内容填满分类。`,
    `- 最终报告说明扫描边界、新增/补充主题、对应文档、已核验的已有知识和剩余缺口；文档数量与零断链均不能单独证明全仓知识完整。`,
    `- 只有完成上述源码调查、确认没有可补内容后才可使用 no_change_needed，并在 summary 中说明覆盖核验范围与依据；禁止仅以代码未变或已有六类骨架为由免更。`,
    `- 完成调查与发布后再调用 maintenance.complete；即使提交哈希没有变化，也必须生成本次新的完成记录。未完成调查、发布失败或存在未解决断链时不得提前调用 complete。`,
    ``,
  ];
}
